/**
 * Download openly licensed landmark photos into public/images/places/.
 * Sources: Wikimedia Commons (CC BY-SA / public domain).
 *
 *   npm run place-images:download
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(__dirname, "..", "public", "images", "places");

const UA =
  "PanoraGoPlaceImageFetcher/1.0 (https://github.com/local/panora-go; tourism seed imagery)";

