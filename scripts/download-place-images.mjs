async function resolveImages() {
  const api =
    "https://commons.wikimedia.org/w/api.php?action=query&titles=" +
    encodeURIComponent(FILES.map((f) => f.title).join("|")) +
    "&prop=imageinfo&iiprop=url|extmetadata|size&iiurlwidth=1600&format=json";
  const res = await fetch(api, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`Commons API ${res.status}`);
  const data = await res.json();
  /** @type {Map<string, any>} */
  const byTitle = new Map();
  for (const p of Object.values(data.query?.pages || {})) {
    if (p.missing) continue;
    byTitle.set(p.title, p.imageinfo?.[0]);
  }
  return byTitle;
}

async function download(url, dest) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`Download failed ${res.status}: ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  await writeFile(dest, buf);
  return buf.length;
}

async function main() {
  await mkdir(outDir, { recursive: true });
  const byTitle = await resolveImages();
  const attributionLines = [
    "# Place image attributions",
    "",
    "Regenerated by `npm run place-images:download`.",
    "Do not replace these with scraped Google Maps / Google Images tiles.",
    "",
    "See also the curated table in this folder’s ATTRIBUTION.md (may be richer).",
    "",
  ];

  for (const item of FILES) {
    const ii = byTitle.get(item.title);
    if (!ii) {
      console.log(`MISSING on Commons: ${item.title}`);
      continue;
    }
    const url = (ii.thumburl || ii.url).split("?")[0];
    const artist = (ii.extmetadata?.Artist?.value || "")
      .replace(/<[^>]+>/g, "")
      .trim();
    const license = ii.extmetadata?.LicenseShortName?.value || "see Commons";
    const dest = path.join(outDir, item.file);
    process.stdout.write(`Fetching ${item.file}... `);
    try {
      const bytes = await download(url, dest);
      console.log(`ok (${Math.round(bytes / 1024)} KB) — ${license}`);
      attributionLines.push(
        `## ${item.file}`,
        `- Source: ${ii.descriptionurl}`,
        `- Author: ${artist}`,
        `- License: ${license}`,
        "",
      );
    } catch (err) {
      console.log(`FAILED: ${err.message}`);
    }
  }

  attributionLines.push(
    "## Venue-owned photos needed",
    "",
    "Copper Bean, Mandara Kitchen, Baobab Braai, Mlichi Farm Stay, Caves Edge Lodge building:",
    "use Admin → Media Library for venue-owned photos. Seed uses area/landmark context only.",
    "",
    "## Google Places Photo API",
    "",
    "`npm run place-images:google` — requires Places API key + UI attribution.",
    "",
  );

  await writeFile(
    path.join(outDir, "ATTRIBUTION.generated.md"),
    attributionLines.join("\n"),
    "utf8",
  );
  console.log("Wrote ATTRIBUTION.generated.md (keep curated ATTRIBUTION.md)");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
